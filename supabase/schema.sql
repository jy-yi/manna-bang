-- 매칭 제안 (매칭 생성 + 양쪽 상태 🟡 진행중 + 양쪽 히스토리)
create or replace function public.manna_propose(p_a text, p_b text)
returns text
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_agent  text := public.manna_agent_id();
  v_mid    text;
  v_ano    text;
  v_bno    text;
  v_aname  text;
  v_bname  text;
  v_by     text;
begin
  if v_agent is null then raise exception 'not_agent' using errcode = '42501'; end if;
  if p_a = p_b then raise exception 'same_asset' using errcode = '22023'; end if;
  if not exists (select 1 from public.assets where id = p_a)
     or not exists (select 1 from public.assets where id = p_b) then
    raise exception 'not_found' using errcode = 'P0002';
  end if;

  select public.manna_no(p_a), public.manna_no(p_b),
         (select a.name from public.agents a join public.assets s on s.agent_id = a.id where s.id = p_a),
         (select a.name from public.agents a join public.assets s on s.agent_id = a.id where s.id = p_b),
         (select a.name from public.agents a where a.id = v_agent)
    into v_ano, v_bno, v_aname, v_bname, v_by;

  insert into public.matches (a_id, b_id, sent_from, stage)
  values (p_a, p_b, 'a', '제안중')
  returning id into v_mid;

  update public.assets set status = 'progress', updated_at = now() where id in (p_a, p_b);

  insert into public.asset_history (asset_id, at, by_name, body) values
    (p_a, current_date, v_by,
     '매물 #' || v_bno || '(' || v_bname || ' 담당)에게 매칭 제안. 매칭 #' || replace(v_mid, 'mt', '') || ' 생성.'),
    (p_b, current_date, v_by,
     '매물 #' || v_ano || '(' || v_aname || ' 담당)의 매칭 제안 도착. 매칭 #' || replace(v_mid, 'mt', '') || '.');

  return v_mid;
end $$;

-- 매칭 단계 변경 (양쪽 상태 + 양쪽 히스토리)
create or replace function public.manna_set_stage(p_mid text, p_stage text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_agent text := public.manna_agent_id();
  v_m     public.matches;
  v_prev  text;
  v_ano   text;
  v_bno   text;
  v_by    text;
  v_status text;
begin
  if v_agent is null then raise exception 'not_agent' using errcode = '42501'; end if;
  select * into v_m from public.matches where id = p_mid;
  if v_m.id is null then raise exception 'not_found' using errcode = 'P0002'; end if;
  if p_stage not in ('제안중','일정 조율','만남 완료','애프터','성사','패스') then
    raise exception 'bad_stage' using errcode = '22023';
  end if;

  v_prev := v_m.stage;
  v_status := case when p_stage = '성사' then 'matched'
                   when p_stage = '패스' then 'available'
                   else 'progress' end;

  select public.manna_no(v_m.a_id), public.manna_no(v_m.b_id),
         (select a.name from public.agents a where a.id = v_agent)
    into v_ano, v_bno, v_by;

  update public.matches set stage = p_stage where id = p_mid;
  update public.assets set status = v_status, updated_at = now() where id in (v_m.a_id, v_m.b_id);

  insert into public.asset_history (asset_id, at, by_name, body) values
    (v_m.a_id, current_date, v_by,
     '매칭 #' || replace(p_mid, 'mt', '') || ' 단계 변경: ' || v_prev || ' → ' || p_stage || ' (매물 #' || v_bno || ')'),
    (v_m.b_id, current_date, v_by,
     '매칭 #' || replace(p_mid, 'mt', '') || ' 단계 변경: ' || v_prev || ' → ' || p_stage || ' (매물 #' || v_ano || ')');
end $$;

-- 매물 삭제 (연결된 매칭 정리 + 상대 매물 상태 되돌리기 + 히스토리)
create or replace function public.manna_delete_asset(p_id text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_agent text := public.manna_agent_id();
  v_owner text;
  v_name  text;
  v_no    text;
  v_by    text;
  m       record;
  v_other text;
begin
  if v_agent is null then raise exception 'not_agent' using errcode = '42501'; end if;
  select agent_id into v_owner from public.assets where id = p_id;
  if v_owner is null then raise exception 'not_found' using errcode = 'P0002'; end if;
  if not (v_owner = v_agent or public.is_owner()) then
    raise exception 'forbidden' using errcode = '42501';
  end if;

  select public.manna_no(p_id), (select name from public.agents where id = v_agent)
    into v_no, v_by;

  for m in select * from public.matches where a_id = p_id or b_id = p_id loop
    v_other := case when m.a_id = p_id then m.b_id else m.a_id end;
    update public.assets
       set status = 'available', updated_at = now()
     where id = v_other and status in ('progress', 'matched');
    insert into public.asset_history (asset_id, at, by_name, body)
    values (v_other, current_date, v_by,
      '매물 #' || v_no || '이(가) 삭제되어 매칭 #' || replace(m.id, 'mt', '') || '이(가) 정리되었습니다.');
  end loop;

  delete from public.matches where a_id = p_id or b_id = p_id;
  delete from public.assets where id = p_id;
end $$;

