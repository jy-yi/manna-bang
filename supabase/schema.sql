-- 사용법
--   1) Supabase 대시보드 → SQL Editor → New query
--   2) 이 파일 전체를 붙여 넣고 RUN
--   3) 여러 번 실행해도 안전합니다 (테이블은 if not exists, 정책은 drop 후 create).
--
-- 설계 원칙
--   · 주선자 비밀번호는 이 파일에 절대 넣지 않습니다. 계정 생성/비번 초기화는
--     manna-admin Edge Function(bootstrap / reset_pin)이 service_role 로만 합니다.
--   · 읽기: 앱은 rpc('manna_state') 한 번으로 필요한 데이터를 받습니다.
--     - 손님(guest@manna.local)은 비고(memo)와 히스토리가 빠지고, 비공개 마담 리뷰도 빠집니다.
--   · 쓰기: 매물·매칭·히스토리는 rpc 함수(security definer)로만 가능하고,
--     함수 안에서 "내 담당인지 / 주선자인지 / 방장인지"를 서버에서 다시 검사합니다.
--   · 사진: manna-photos 비공개 버킷 + 서명 URL(createSignedUrl)로만 표시.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 0. 번호 발급기 (기존 프로토타입의 p31, mt7, rv101 규칙을 그대로 잇습니다)
-- ---------------------------------------------------------------------------
create sequence if not exists public.asset_seq   start with 31;
create sequence if not exists public.match_seq   start with 7;
create sequence if not exists public.review_seq  start with 101;

-- ---------------------------------------------------------------------------
-- 1. 테이블
-- ---------------------------------------------------------------------------

-- 주선자 (ag1 ~ ag9). auth_uid 는 Supabase Auth 사용자와 연결되는 고리입니다.
create table if not exists public.agents (
  id          text primary key,
  name        text not null,
  emoji       text not null default '🌿',
  role        text not null default '주선자',
  active      boolean not null default true,
  is_owner    boolean not null default false,
  auth_uid    uuid unique references auth.users(id) on delete set null,
  created_at  timestamptz not null default now()
);

-- 매물. id(p31…)가 곧 사람이 보는 등록 번호입니다.
create table if not exists public.assets (
  id          text primary key default ('p' || nextval('public.asset_seq')::text),
  agent_id    text not null references public.agents(id) on update cascade on delete restrict,
  gender      text not null check (gender in ('M','F')),
  birth       int  not null check (birth between 1900 and 2020),
  height      int  not null check (height between 100 and 250),
  region      text not null default '',
  work_area   text not null default '',
  job         text not null default '',
  company     text not null default '',
  mbti        text not null default '',
  smoke       text not null default '',
  drink       text not null default '',
  tags        text[] not null default '{}',
  wants       text[] not null default '{}',
  extras      jsonb  not null default '[]'::jsonb,
  memo        text not null default '',         -- 주선자만 보는 비고
  comment     text not null default '',         -- 주선자 코멘트(손님도 열람)
  status      text not null default 'available'
              check (status in ('available','progress','matched','hold')),
  photos      jsonb not null default '[]'::jsonb,  -- Storage 경로 배열, [0]=대표
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists assets_agent_idx on public.assets(agent_id);
create index if not exists assets_status_idx on public.assets(status);

-- 매칭 (제안 → 일정 조율 → … → 성사/패스)
create table if not exists public.matches (
  id          text primary key default ('mt' || nextval('public.match_seq')::text),
  a_id        text not null references public.assets(id) on delete cascade,
  b_id        text not null references public.assets(id) on delete cascade,
  sent_from   text not null default 'a' check (sent_from in ('a','b')),
  stage       text not null default '제안중'
              check (stage in ('제안중','일정 조율','만남 완료','애프터','성사','패스')),
  created_at  timestamptz not null default now(),
  constraint matches_pair_chk check (a_id <> b_id)
);
create index if not exists matches_a_idx on public.matches(a_id);
create index if not exists matches_b_idx on public.matches(b_id);

-- 마담 리뷰 (매칭 1건 × 매물 1건 × 작성자 1명 = 1개)
create table if not exists public.reviews (
  id          text primary key default ('rv' || nextval('public.review_seq')::text),
  asset_id    text not null references public.assets(id) on delete cascade,
  match_id    text references public.matches(id) on delete cascade,
  by_agent    text not null references public.agents(id),
  vis         text not null default 'public' check (vis in ('public','private')),
  body        text not null,
  created_at  timestamptz not null default now(),
  unique (asset_id, match_id, by_agent)
);
create index if not exists reviews_asset_idx on public.reviews(asset_id);

-- 진행 히스토리
create table if not exists public.asset_history (
  id          bigint generated by default as identity primary key,
  asset_id    text not null references public.assets(id) on delete cascade,
  at          date not null default current_date,
  by_name     text not null default '',
  body        text not null,
  created_at  timestamptz not null default now()
);
create index if not exists asset_history_asset_idx on public.asset_history(asset_id, at desc, id desc);

