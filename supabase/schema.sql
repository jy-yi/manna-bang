-- 지금 로그인한 사람의 주선자 id (주선자가 아니면 null)
create or replace function public.manna_agent_id()
returns text
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select a.id from public.agents a where a.auth_uid = auth.uid() and a.active limit 1;
$$;

create or replace function public.is_agent()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$ select public.manna_agent_id() is not null; $$;

create or replace function public.is_owner()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.agents a
    where a.auth_uid = auth.uid() and a.active and a.is_owner
  );
$$;

-- 손님 = 로그인은 했지만 주선자 명단에 없는 계정 (guest@manna.local)
create or replace function public.is_guest()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$ select auth.uid() is not null and not public.is_agent(); $$;

-- jsonb → text[] / jsonb[] 안전 변환
create or replace function public.manna_text_array(j jsonb)
returns text[]
language plpgsql
immutable
as $$
begin
  if j is null or jsonb_typeof(j) <> 'array' then return '{}'::text[]; end if;
  return coalesce((select array_agg(value) from jsonb_array_elements_text(j)), '{}'::text[]);
end $$;

create or replace function public.manna_json_array(j jsonb)
returns jsonb
language sql
immutable
as $$
  select case when jsonb_typeof(j) = 'array' then j else '[]'::jsonb end;
$$;

-- 'p31' → '31', 'mt7' → '07' (앱의 assetNo 표기와 같게)
create or replace function public.manna_no(p text)
returns text
language sql
immutable
as $$
  select lpad(regexp_replace(coalesce(p,''), '[^0-9]', '', 'g'), 2, '0');
$$;

-- ---------------------------------------------------------------------------
-- 4. 읽기 — 앱이 쓰는 단 하나의 조회 함수
--    손님에게는 memo·history·비공개 리뷰를 아예 내려보내지 않습니다.
-- ---------------------------------------------------------------------------
create or replace function public.manna_state()
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_agent text := public.manna_agent_id();
  v_guest boolean;
  v_out   jsonb;
begin
  if auth.uid() is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;
  v_guest := (v_agent is null);

  select jsonb_build_object(
    'agents', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', a.id, 'name', a.name, 'emoji', a.emoji, 'role', a.role,
        'active', a.active, 'is_owner', a.is_owner) order by a.id)
      from public.agents a), '[]'::jsonb),

    'assets', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', s.id,
        'agent', s.agent_id,
        'gender', s.gender,
        'birth', s.birth,
        'height', s.height,
        'region', s.region,
        'workArea', s.work_area,
        'job', s.job,
        'company', s.company,
        'mbti', s.mbti,
        'smoke', s.smoke,
        'drink', s.drink,
        'tags', to_jsonb(s.tags),
        'wants', to_jsonb(s.wants),
        'extras', s.extras,
        'memo', case when v_guest then '' else s.memo end,
        'comment', s.comment,
        'status', s.status,
        'photos', s.photos,
        'createdAt', to_char(s.created_at, 'YYYY-MM-DD')) order by s.id)
      from public.assets s), '[]'::jsonb),

    'matches', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', m.id, 'aId', m.a_id, 'bId', m.b_id, 'from', m.sent_from,
        'stage', m.stage, 'at', to_char(m.created_at, 'YYYY-MM-DD')) order by m.id)
      from public.matches m), '[]'::jsonb),

    'reviews', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', r.id, 'assetId', r.asset_id, 'matchId', r.match_id, 'by', r.by_agent,
        'vis', r.vis, 'text', r.body, 'at', to_char(r.created_at, 'YYYY-MM-DD'))
        order by r.created_at desc, r.id desc)
      from public.reviews r
      where (v_guest and r.vis = 'public')
         or (not v_guest and (r.vis = 'public' or r.by_agent = v_agent))), '[]'::jsonb),

    'history', case when v_guest then '[]'::jsonb else coalesce((
      select jsonb_agg(jsonb_build_object(
        'assetId', h.asset_id, 'at', to_char(h.at, 'YYYY-MM-DD'),
        'by', h.by_name, 'text', h.body) order by h.at desc, h.id desc)
      from public.asset_history h), '[]'::jsonb) end
  ) into v_out;

  return v_out;
end $$;

