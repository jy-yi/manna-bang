-- assets: 손님·주선자 모두 클라이언트 직접 select 불가 (rpc manna_state 사용)
drop policy if exists manna_assets_read_agent on public.assets;
create policy manna_assets_read_agent on public.assets
  for select to authenticated using (public.is_agent());

-- matches: 주선자만 읽기 (손님은 rpc manna_state 로 필요한 것만)
drop policy if exists manna_matches_read_agent on public.matches;
create policy manna_matches_read_agent on public.matches
  for select to authenticated using (public.is_agent());

