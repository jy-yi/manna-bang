-- 매물 등록/수정. p_id 가 null/'' 이면 새 매물(p31…)을 만들고 id를 돌려줍니다.
create or replace function public.manna_save_asset(p_id text, p_data jsonb, p_history text default '')
returns text
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_agent text := public.manna_agent_id();
  v_id    text := nullif(btrim(coalesce(p_id, '')), '');
  v_owner text;
  v_name  text;
begin
  if v_agent is null then raise exception 'not_agent' using errcode = '42501'; end if;
  select name into v_name from public.agents where id = v_agent;

  if v_id is null then
    insert into public.assets (
      agent_id, gender, birth, height, region, work_area, job, company, mbti, smoke, drink,
      tags, wants, extras, memo, comment, status, photos)
    values (
      v_agent,
      coalesce(nullif(p_data->>'gender', ''), 'M'),
      coalesce(nullif(p_data->>'birth', '')::int, 1995),
      coalesce(nullif(p_data->>'height', '')::int, 170),
      coalesce(p_data->>'region', ''),
      coalesce(p_data->>'workArea', ''),
      coalesce(p_data->>'job', ''),
      coalesce(p_data->>'company', ''),
      coalesce(p_data->>'mbti', ''),
      coalesce(p_data->>'smoke', ''),
      coalesce(p_data->>'drink', ''),
      public.manna_text_array(p_data->'tags'),
      public.manna_text_array(p_data->'wants'),
      public.manna_json_array(p_data->'extras'),
      coalesce(p_data->>'memo', ''),
      coalesce(p_data->>'comment', ''),
      coalesce(nullif(p_data->>'status', ''), 'available'),
      public.manna_json_array(p_data->'photos'))
    returning id into v_id;
  else
    select agent_id into v_owner from public.assets where id = v_id;
    if v_owner is null then raise exception 'not_found' using errcode = 'P0002'; end if;
    if not (v_owner = v_agent or public.is_owner()) then
      raise exception 'forbidden' using errcode = '42501';
    end if;

    update public.assets set
      gender    = coalesce(nullif(p_data->>'gender', ''), gender),
      birth     = coalesce(nullif(p_data->>'birth', '')::int, birth),
      height    = coalesce(nullif(p_data->>'height', '')::int, height),
      region    = coalesce(p_data->>'region', region),
      work_area = coalesce(p_data->>'workArea', work_area),
      job       = coalesce(p_data->>'job', job),
      company   = coalesce(p_data->>'company', company),
      mbti      = coalesce(p_data->>'mbti', mbti),
      smoke     = coalesce(p_data->>'smoke', smoke),
      drink     = coalesce(p_data->>'drink', drink),
      tags      = case when p_data ? 'tags'   then public.manna_text_array(p_data->'tags')   else tags   end,
      wants     = case when p_data ? 'wants'  then public.manna_text_array(p_data->'wants')  else wants  end,
      extras    = case when p_data ? 'extras' then public.manna_json_array(p_data->'extras') else extras end,
      memo      = coalesce(p_data->>'memo', memo),
      comment   = coalesce(p_data->>'comment', comment),
      status    = coalesce(nullif(p_data->>'status', ''), status),
      photos    = case when p_data ? 'photos' then public.manna_json_array(p_data->'photos') else photos end,
      updated_at = now()
    where id = v_id;
  end if;

  if btrim(coalesce(p_history, '')) <> '' then
    insert into public.asset_history (asset_id, at, by_name, body)
    values (v_id, current_date, v_name, p_history);
  end if;

  return v_id;
end $$;

-- 매물 상태 변경 (+ 히스토리 한 줄)
create or replace function public.manna_set_status(p_id text, p_status text, p_history text default '')
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_agent text := public.manna_agent_id();
  v_owner text;
  v_name  text;
begin
  if v_agent is null then raise exception 'not_agent' using errcode = '42501'; end if;
  select agent_id into v_owner from public.assets where id = p_id;
  if v_owner is null then raise exception 'not_found' using errcode = 'P0002'; end if;
  if not (v_owner = v_agent or public.is_owner()) then
    raise exception 'forbidden' using errcode = '42501';
  end if;

  update public.assets set status = p_status, updated_at = now() where id = p_id;

  if btrim(coalesce(p_history, '')) <> '' then
    select name into v_name from public.agents where id = v_agent;
    insert into public.asset_history (asset_id, at, by_name, body)
    values (p_id, current_date, v_name, p_history);
  end if;
end $$;

-- 히스토리에 메모 한 줄 추가
create or replace function public.manna_add_history(p_id text, p_text text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_agent text := public.manna_agent_id();
  v_owner text;
  v_name  text;
begin
  if v_agent is null then raise exception 'not_agent' using errcode = '42501'; end if;
  if btrim(coalesce(p_text, '')) = '' then raise exception 'empty_text' using errcode = '22023'; end if;
  select agent_id into v_owner from public.assets where id = p_id;
  if v_owner is null then raise exception 'not_found' using errcode = 'P0002'; end if;
  if not (v_owner = v_agent or public.is_owner()) then
    raise exception 'forbidden' using errcode = '42501';
  end if;
  select name into v_name from public.agents where id = v_agent;
  insert into public.asset_history (asset_id, at, by_name, body)
  values (p_id, current_date, v_name, btrim(p_text));
end $$;

-- 내 이모지 변경
create or replace function public.manna_set_emoji(p_emoji text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_agent text := public.manna_agent_id();
