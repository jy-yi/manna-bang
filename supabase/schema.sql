drop policy if exists manna_history_read_agent on public.asset_history;
create policy manna_history_read_agent on public.asset_history
  for select to authenticated using (public.is_agent());

-- reviews: 손님은 공개(vis='public')만, 주선자는 전체
drop policy if exists manna_reviews_read on public.reviews;
drop policy if exists manna_reviews_insert on public.reviews;
drop policy if exists manna_reviews_update on public.reviews;
drop policy if exists manna_reviews_delete on public.reviews;
create policy manna_reviews_read on public.reviews
  for select to authenticated
  using (public.is_agent() or vis = 'public');
create policy manna_reviews_insert on public.reviews
  for insert to authenticated
  with check (public.is_agent() and by_agent = public.manna_agent_id());
create policy manna_reviews_update on public.reviews
  for update to authenticated
  using (public.is_agent() and by_agent = public.manna_agent_id())
  with check (public.is_agent() and by_agent = public.manna_agent_id());
create policy manna_reviews_delete on public.reviews
  for delete to authenticated
  using (public.is_agent() and by_agent = public.manna_agent_id());

